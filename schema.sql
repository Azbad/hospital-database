DROP TABLE IF EXISTS Patients CASCADE;
DROP TABLE IF EXISTS Receptionists CASCADE;
DROP TABLE IF EXISTS Nurses CASCADE;
DROP TABLE IF EXISTS Rooms CASCADE;
DROP TABLE IF EXISTS Doctors CASCADE;
DROP TABLE IF EXISTS Departments CASCADE;
CREATE TABLE Departments(
    department_id INT PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
    department_name VARCHAR(100) NOT NULL,
    department_description VARCHAR (100) NOT NULL,
    head_of_departments_id INT
);
CREATE TABLE Doctors(
    doctor_id INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(40),
    specialty VARCHAR(100),
    department_id INT,
    house_address VARCHAR(100),
    FOREIGN KEY(department_id) REFERENCES Departments(department_id)
);
ALTER TABLE Departments
ADD FOREIGN KEY(head_of_departments_id) REFERENCES Doctors(doctor_id) ON DELETE
SET NULL;
CREATE TABLE Rooms(
    room_id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    room_number VARCHAR(10) NOT NULL,
    department_id INT,
    FOREIGN KEY(department_id) REFERENCES Departments(department_id)
);
CREATE TABLE Nurses(
    nurse_id INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(40),
    house_address VARCHAR(100)
);
CREATE TABLE Receptionists(
    receptionist_id INT PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(40),
    house_address VARCHAR(100)
);
CREATE TABLE Patients(
    Patient_id INT PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(40),
    entry_date DATE NOT NULL,
    exit_date DATE,
    doctor_assigned INT,
    nurse_assigned INT,
    reception_guide INT,
    FOREIGN KEY(doctor_assigned) REFERENCES Doctors(doctor_id) ON DELETE
    SET NULL,
        FOREIGN KEY(nurse_assigned) REFERENCES Nurses(nurse_id) ON DELETE
    SET NULL,
        FOREIGN KEY(reception_guide) REFERENCES Receptionists(receptionist_id) ON DELETE
    SET NULL
);
ALTER TABLE Patients
ADD COLUMN room_assigned INT,
    ADD FOREIGN KEY(room_assigned) REFERENCES Rooms(room_id);
